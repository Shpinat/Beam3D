    public MeshGeometry3D GenerateMesh(VolumeData volume, double isolevel)
    {
        var builder = new MeshBuilder();

        int width = volume.Width;
        int height = volume.Height;
        int depth = volume.Depth;

        int step = Math.Max(1, Math.Max(width, height) / 64);

        for (int z = 0; z < depth - step; z += step)
        {
            for (int y = 0; y < height - step; y += step)
            {
                for (int x = 0; x < width - step; x += step)
                {
                    double[] values = new double[8];
                    values[0] = GetValue(volume, x, y, z);
                    values[1] = GetValue(volume, x + step, y, z);
                    values[2] = GetValue(volume, x + step, y + step, z);
                    values[3] = GetValue(volume, x, y + step, z);
                    values[4] = GetValue(volume, x, y, z + step);
                    values[5] = GetValue(volume, x + step, y, z + step);
                    values[6] = GetValue(volume, x + step, y + step, z + step);
                    values[7] = GetValue(volume, x, y + step, z + step);

                    int cubeIndex = 0;
                    if (values[0] < isolevel) cubeIndex |= 1;
                    if (values[1] < isolevel) cubeIndex |= 2;
                    if (values[2] < isolevel) cubeIndex |= 4;
                    if (values[3] < isolevel) cubeIndex |= 8;
                    if (values[4] < isolevel) cubeIndex |= 16;
                    if (values[5] < isolevel) cubeIndex |= 32;
                    if (values[6] < isolevel) cubeIndex |= 64;
                    if (values[7] < isolevel) cubeIndex |= 128;

                    if (EdgeTable[cubeIndex] == 0)
                        continue;

                    var p = new Vector3[8];
                    p[0] = new Vector3(x, y, z);
                    p[1] = new Vector3(x + step, y, z);
                    p[2] = new Vector3(x + step, y + step, z);
                    p[3] = new Vector3(x, y + step, z);
                    p[4] = new Vector3(x, y, z + step);
                    p[5] = new Vector3(x + step, y, z + step);
                    p[6] = new Vector3(x + step, y + step, z + step);
                    p[7] = new Vector3(x, y + step, z + step);

                    var vertList = new Vector3[12];
                    if ((EdgeTable[cubeIndex] & 1) != 0) vertList[0] = Interpolate(isolevel, p[0], p[1], values[0], values[1]);
                    if ((EdgeTable[cubeIndex] & 2) != 0) vertList[1] = Interpolate(isolevel, p[1], p[2], values[1], values[2]);
                    if ((EdgeTable[cubeIndex] & 4) != 0) vertList[2] = Interpolate(isolevel, p[2], p[3], values[2], values[3]);
                    if ((EdgeTable[cubeIndex] & 8) != 0) vertList[3] = Interpolate(isolevel, p[3], p[0], values[3], values[0]);
                    if ((EdgeTable[cubeIndex] & 16) != 0) vertList[4] = Interpolate(isolevel, p[4], p[5], values[4], values[5]);
                    if ((EdgeTable[cubeIndex] & 32) != 0) vertList[5] = Interpolate(isolevel, p[5], p[6], values[5], values[6]);
                    if ((EdgeTable[cubeIndex] & 64) != 0) vertList[6] = Interpolate(isolevel, p[6], p[7], values[6], values[7]);
                    if ((EdgeTable[cubeIndex] & 128) != 0) vertList[7] = Interpolate(isolevel, p[7], p[4], values[7], values[4]);
                    if ((EdgeTable[cubeIndex] & 256) != 0) vertList[8] = Interpolate(isolevel, p[0], p[4], values[0], values[4]);
                    if ((EdgeTable[cubeIndex] & 512) != 0) vertList[9] = Interpolate(isolevel, p[1], p[5], values[1], values[5]);
                    if ((EdgeTable[cubeIndex] & 1024) != 0) vertList[10] = Interpolate(isolevel, p[2], p[6], values[2], values[6]);
                    if ((EdgeTable[cubeIndex] & 2048) != 0) vertList[11] = Interpolate(isolevel, p[3], p[7], values[3], values[7]);

                    for (int i = 0; TriTable[cubeIndex, i] != -1; i += 3)
                    {
                        var p1 = vertList[TriTable[cubeIndex, i]];
                        var p2 = vertList[TriTable[cubeIndex, i + 1]];
                        var p3 = vertList[TriTable[cubeIndex, i + 2]];

                        builder.Positions.Add(p1);
                        builder.Positions.Add(p2);
                        builder.Positions.Add(p3);
                        int count = builder.Positions.Count;
                        builder.TriangleIndices.Add(count - 3);
                        builder.TriangleIndices.Add(count - 2);
                        builder.TriangleIndices.Add(count - 1);
                    }
                }
            }
        }

        var geometry = builder.ToMesh();

        return geometry;
    }

    private double GetValue(VolumeData volume, int x, int y, int z)
    {
        if (x < 0 || x >= volume.Width || y < 0 || y >= volume.Height || z < 0 || z >= volume.Depth) return -1000;
        return volume.Data[z * volume.Width * volume.Height + y * volume.Width + x];
    }

    private Vector3 Interpolate(double isolevel, Vector3 p1, Vector3 p2, double valp1, double valp2)
    {
        if (Math.Abs(isolevel - valp1) < 0.00001) return p1;
        if (Math.Abs(isolevel - valp2) < 0.00001) return p2;
        if (Math.Abs(valp1 - valp2) < 0.00001) return p1;
        double mu = (isolevel - valp1) / (valp2 - valp1);
        return new Vector3(
            (float)(p1.X + mu * (p2.X - p1.X)),
            (float)(p1.Y + mu * (p2.Y - p1.Y)),
            (float)(p1.Z + mu * (p2.Z - p1.Z))
        );
    }
